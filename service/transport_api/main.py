"""The FastAPI application.

It runs beside the PHP application, never in front of it: nginx picks between
the two by path prefix. Every route declared here therefore lives under /v2,
and nothing outside that prefix is served - a request for /v1 arriving here is
a routing mistake, and answering it would silently shadow the contract the PHP
application owns.

The /v1 compatibility layer planned for stage S4 will be a second router in
this same application, mounted deliberately and routed only once it has been
proven identical.
"""

from datetime import datetime
from typing import Literal
from zoneinfo import ZoneInfo

from fastapi import APIRouter, FastAPI
from pydantic import BaseModel, Field

from . import settings

PREFIX = "/v2"

app = FastAPI(
    title="transport.opendata.ch",
    version=settings.VERSION,
    summary="The Swiss public transport API",
    # FastAPI's own documents are served under the prefix as well, so that the
    # nginx location block is the only thing that has to know about /v2. The
    # Swagger 2.0 document of /v1 is generated by the PHP application and is a
    # different document at a different address; the two never meet.
    openapi_url=f"{PREFIX}/openapi.json",
    docs_url=f"{PREFIX}/docs",
    redoc_url=None,
)

router = APIRouter(prefix=PREFIX)


class Health(BaseModel):
    """What the service says about itself."""

    status: Literal["ok"] = "ok"
    version: str = Field(description="Short commit SHA of the image, or 'dev'.")
    timezone: str = Field(description="The zone all local times are expressed in.")
    time: datetime = Field(description="Now, in that zone, with its offset.")


@router.get("/health", summary="Liveness and identity of the service")
def health() -> Health:
    """Answer who is running and in which timezone.

    The timestamp is not decoration: it carries the offset, so a container that
    came up on UTC says so in the smoke test instead of in the data months
    later.
    """
    return Health(
        version=settings.VERSION,
        timezone=settings.TIMEZONE,
        time=datetime.now(ZoneInfo(settings.TIMEZONE)),
    )


app.include_router(router)
