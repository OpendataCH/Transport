"""The FastAPI application.

It runs beside the PHP application, never in front of it: nginx picks between
the two by path prefix. Every route declared here lives under /v2, and nothing
outside that prefix is served - a request for /v1 arriving here is a routing
mistake, and answering it would silently shadow the contract the PHP
application owns.

/v2 answers the same questions in the same shape as /v1. That is the whole
design: the two can then be compared request by request, and once they have
been identical on real traffic for long enough, /v1 is routed here and the PHP
stack is retired. A cleaner shape would have meant a second contract to
maintain forever, and no way to test the first one.
"""

from contextlib import asynccontextmanager
from datetime import datetime
from typing import Literal
from zoneinfo import ZoneInfo

from fastapi import APIRouter, FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from uvicorn.middleware.proxy_headers import ProxyHeadersMiddleware

from . import connections, errors, locations, settings, stationboard, upstream
from .models import ApiInfo

PREFIX = "/v2"


@asynccontextmanager
async def lifespan(app: FastAPI):
    """One connection pool for the life of the process, not one per request."""
    app.state.http = upstream.build_client()
    try:
        yield
    finally:
        await app.state.http.aclose()


app = FastAPI(
    title="transport.opendata.ch",
    version=settings.VERSION,
    summary="The Swiss public transport API",
    description=(
        "The same API as `/v1` - same endpoints, same parameters, same JSON - "
        "served beside it by a separate service written in Python.\n\n"
        "Data comes from [search.ch](https://timetable.search.ch/). This "
        "service translates; it stores nothing."
    ),
    lifespan=lifespan,
    # FastAPI's own documents are served under the prefix as well, so that the
    # nginx location block is the only thing that has to know about /v2. The
    # Swagger 2.0 document of /v1 is generated by the PHP application and is a
    # different document at a different address; the two never meet.
    openapi_url=f"{PREFIX}/openapi.json",
    docs_url=f"{PREFIX}/docs",
    redoc_url=None,
)

# X-Forwarded-For becomes the request's client address. This is the single
# most consequential line in the service: search.ch rate-limits on the caller
# we name, so without it every caller in the world shares one bucket and
# throttles each other - and the only symptom is a rise in 429s. It is done
# here rather than by a uvicorn flag so that a test can exercise it.
# Trusting every proxy is safe because the container is never reached except
# through the nginx in front of it.
app.add_middleware(ProxyHeadersMiddleware, trusted_hosts="*")

# Browsers call this API directly, as they always have on /v1.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)

errors.install(app)

router = APIRouter(prefix=PREFIX)


class Health(BaseModel):
    """What the service says about itself."""

    status: Literal["ok"] = "ok"
    version: str = Field(description="Short commit SHA of the image, or 'dev'.")
    timezone: str = Field(description="The zone all local times are expressed in.")
    time: datetime = Field(description="Now, in that zone, with its offset.")


@router.get("/health", summary="Liveness and identity of the service")
def health() -> Health:
    """Answer who is running and in which timezone.

    The timestamp is not decoration: it carries the offset, so a container that
    came up on UTC says so in the smoke test instead of in the data months
    later.
    """
    return Health(
        version=settings.VERSION,
        timezone=settings.TIMEZONE,
        time=datetime.now(ZoneInfo(settings.TIMEZONE)),
    )


@router.get("/", summary="What this API is")
def info() -> ApiInfo:
    """The same answer `/v1/` gives, with its own version number."""
    return ApiInfo(
        date=datetime.now(ZoneInfo(settings.TIMEZONE)).isoformat(timespec="seconds"),
        author="Opendata.ch",
        version="2.0",
    )


router.include_router(locations.router, tags=["locations"])
router.include_router(stationboard.router, tags=["stationboard"])
router.include_router(connections.router, tags=["connections"])

app.include_router(router)
